// compose-catalogue.mjs — what Ask Suvat's reader is told about the pieces it
// may compose a scene from: the backdrops, the figures, the effects and the
// engines, each engine's numbers and the answers it gives. Generated from
// js/compose/registry.js, so the reader can never name a piece, a number or
// an answer the app does not have; test/compose.test.mjs fails if
// worker/src/compose.js is out of date. Run: node tools/compose-catalogue.mjs

import fs from 'node:fs';
import path from 'node:path';
import { BACKDROPS, FIGURES, EFFECTS, ENGINES, CARRIERS } from '../js/compose/registry.js';
import { compose } from '../js/compose/recipe.js';
import { answersFor } from '../js/parts/answers.js';

const ROOT = path.resolve(import.meta.dirname, '..');
/** One recipe per engine, to ask the app which answers it offers. */
const sample = {
  projectile: { backdrop: 'cliff', objects: [{ figure: 'car' }] },
  pair: { backdrop: 'tower', objects: [{ figure: 'ball' }, { figure: 'ball' }] },
  bounce: { backdrop: 'hall', objects: [{ figure: 'ball' }] },
  twin: { backdrop: 'cliff', objects: [{ figure: 'ball' }, { figure: 'stone' }] },
};

export function catalogue() {
  const ready = Object.entries(ENGINES).filter(([, E]) => E.ready);
  const lines = [
    'backdrops (where it happens):',
    ...Object.entries(BACKDROPS).map(([k, B]) => `  ${k} — ${B.what}${B.edge ? '; it is launched from its top, so it needs h' : ''}`),
    'figures (what moves):',
    ...Object.entries(FIGURES).map(([k, F]) => `  ${k} — ${F.label}${F.thrown ? ', thrown by a person' : ''}${F.views.includes('side') ? '' : ' (seen from above only)'}`),
    'carriers (backdrop air only, as "carrier": what it is let go from; balloon if left out):',
    `  ${Object.entries(CARRIERS).map(([k, C]) => `${k} — ${C.label}`).join('; ')}`,
    'effects (optional; the app picks one from what it lands on):',
    ...Object.entries(EFFECTS).map(([k, X]) => `  ${k} — ${X.label}, ${X.what}`),
    'engines (how it moves):',
    ...ready.map(([k, E]) => {
      const s = compose({ engine: k, ...sample[k] });
      const answers = s.ok ? answersFor(s.scenario).map((a) => `${a.key} = ${a.say}`).join('; ') : 'none';
      return [`  ${k} — ${E.what}; ${E.objects[0] === E.objects[1] ? E.objects[0] : `${E.objects[0]} to ${E.objects[1]}`} object${E.objects[1] > 1 ? 's' : ''}`,
        `    numbers: ${Object.entries(E.boxes).map(([b, say]) => `${b} = ${say}`).join('; ')}`,
        `    answers: ${answers}`].join('\n');
    }),
  ];
  return { engines: ready.map(([k]) => k), guide: lines.join('\n') };
}

export function source() {
  const { engines, guide } = catalogue();
  return `// compose.js — GENERATED by tools/compose-catalogue.mjs from
// js/compose/registry.js. Do not edit: run \`node tools/compose-catalogue.mjs\`.

export const COMPOSE_ENGINES = ${JSON.stringify(engines)};

export const COMPOSE_GUIDE = ${JSON.stringify(guide)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.writeFileSync(path.join(ROOT, 'worker/src/compose.js'), source());
  console.log('wrote worker/src/compose.js');
}
