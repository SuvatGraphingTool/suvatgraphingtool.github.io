// reader-catalogue.mjs — what Ask Suvat's reader is told about the Past-paper
// library: each scenario's id, what it is, the boxes it takes and the answers
// its parts give. Generated from js/library.js and js/kits/ so the reader can
// never name a box or an answer the app does not have; test/question.test.mjs
// fails if worker/src/library.js is out of date. Run: node tools/reader-catalogue.mjs

import fs from 'node:fs';
import path from 'node:path';
import { LIBRARY } from '../js/library.js';
import { KITS } from '../js/kits/index.js';
import { SCENARIOS } from '../js/scenarios.js';
import { answersFor, boxesOf } from '../js/parts/answers.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const plain = (s) => String(s ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

/** Every box a kit shows, with what it holds. */
function boxes(s) {
  const K = KITS[s.kit];
  const all = boxesOf(K, s.example || {});
  const seen = new Set(), out = [];
  for (const f of all) {
    if (seen.has(f.key)) continue;
    seen.add(f.key);
    const col = K.cols?.[f.col] ? `${plain(K.cols[f.col])}: ` : '';
    const opts = f.type === 'choice' && f.options ? ` [${f.options.map((o) => o.v).join('|')}]` : '';
    out.push(`${f.key} = ${col}${plain(f.label)}${opts}`);
  }
  if (K.g && !seen.has('g')) out.push('g = g, only if the question states it');
  return out;
}

/** Which boxes one paper filled, words kept and numbers hidden, so the reader
    sees how they go together without a number it could copy. */
const shape = (s) => JSON.stringify(Object.fromEntries(Object.entries(s.example || {})
  .map(([k, v]) => [k, typeof v === 'number' || /^-?[\d.\/]+$/.test(String(v)) ? '#' : v]))).replace(/"#"/g, '#');

export function catalogue() {
  const lib = LIBRARY.map((s) => [
    `${s.id} — ${plain(s.name)}: ${plain(s.sub)}`,
    `  boxes: ${boxes(s).join('; ')}`,
    `  shape: ${shape(s)}`,
    ...(s.reader ? [`  note: ${s.reader}`] : []),
    `  answers: ${answersFor(s).map((a) => `${a.key} = ${plain(a.say)}`).join('; ') || 'none'}`,
  ].join('\n')).join('\n');
  const orig = ['up', 'road'].map((id) => SCENARIOS.find((x) => x.id === id))
    .map((s) => `${s.id === 'road' ? 'road' : 'every projectile scenario'}: ${answersFor(s).map((a) => `${a.key} = ${a.say}`).join('; ')}`).join('\n');
  return { ids: LIBRARY.map((s) => s.id), lib, orig };
}

export function source() {
  const { ids, lib, orig } = catalogue();
  return `// library.js — GENERATED by tools/reader-catalogue.mjs from js/library.js and
// js/kits/. Do not edit: run \`node tools/reader-catalogue.mjs\`.

export const LIBRARY_IDS = ${JSON.stringify(ids)};

export const LIBRARY_GUIDE = ${JSON.stringify(lib)};

export const ORIGINAL_ANSWERS = ${JSON.stringify(orig)};
`;
}

if (process.argv[1] && process.argv[1].endsWith('reader-catalogue.mjs')) {
  fs.writeFileSync(path.join(ROOT, 'worker/src/library.js'), source());
  console.log(`wrote worker/src/library.js: ${catalogue().ids.length} library scenarios, ${source().length} characters`);
}
